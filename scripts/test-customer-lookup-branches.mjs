import assert from "node:assert/strict";
import { accountBranchLabel, loadCustomerBranches } from "../src/pages/Registry/Customers/Documents/customerBranches.js";
assert.equal(accountBranchLabel([{ BranchDescription: "Main" }, { BranchDescription: "Main" }, { BranchDescription: "West" }]), "Main, West");
assert.equal(accountBranchLabel([]), "No accounts");
assert.equal(accountBranchLabel([{}]), "Unavailable");
assert.equal(accountBranchLabel([{ BranchDescription: "Main" }, {}]), "Main, Unknown branch");
assert.throws(() => accountBranchLabel({}), /Invalid/);
const items = Array.from({ length: 20 }, (_, index) => ({ Id: String(index) }));
const cache = new Map();
let active = 0;
let peak = 0;
let calls = 0;
const labels = new Map();
const fetchAccounts = async () => {
  calls++;
  peak = Math.max(peak, ++active);
  await new Promise((resolve) => setImmediate(resolve));
  active--;
  return [{ BranchDescription: "Main" }];
};
await loadCustomerBranches(items, fetchAccounts, (id, label) => labels.set(id, label), { signal: new AbortController().signal, cache });
assert.equal(calls, 20);
assert.equal(peak, 4);
assert.equal(labels.size, 20);
await loadCustomerBranches(items, fetchAccounts, () => {}, { signal: new AbortController().signal, cache });
assert.equal(calls, 20, "Revisiting cached customers makes no additional calls");
const controller = new AbortController();
let abortedCalls = 0;
await loadCustomerBranches(items, async () => { abortedCalls++; controller.abort(); return []; }, () => assert.fail("Cancelled results must not update the UI"), { signal: controller.signal, cache: new Map() });
assert.equal(abortedCalls, 1, "Cancellation stops queued requests");
const failedCache = new Map();
await loadCustomerBranches([{ Id: "failed" }], async () => { throw new Error("Offline"); }, (id, label) => assert.equal(label, "Unavailable"), { signal: new AbortController().signal, cache: failedCache });
assert.equal(failedCache.size, 0, "Failures are retried on a later search");
console.log("Customer branches passed: multiple branches, deduplication, empty/invalid data, concurrency, cache, cancellation and failure handling.");
