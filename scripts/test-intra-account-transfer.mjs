import assert from "node:assert/strict";
import fs from "node:fs";
import { validateIntraAccountEntry as validate } from "../src/pages/Accounts/IntraAccountTransfer/validation.js";
const source = { Id: "source", CustomerId: "member", CustomerAccountTypeProductCode: 1, AvailableBalance: 200 };
const target = { Id: "loan", CustomerId: "member", CustomerAccountTypeProductCode: 2, PrincipalBalance: -100, InterestBalance: -20 };
const form = { ApportionTo: 1, Principal: 100, Interest: 20 };
assert.equal(validate(form, source, target, []), "");
assert.match(validate({ ...form, CustomerAccountId: "new-selection" }, source, target, []), /selected destination/);
assert.match(validate({ ...form, ApportionTo: 2 }, source, target, []), /another customer account/);
assert.match(validate(form, source, { ...target, CustomerId: "other" }, []), /belonging/);
assert.match(validate(form, source, { ...target, Id: "source" }, []), /differ/);
assert.match(validate(form, { ...source, CustomerAccountTypeProductCode: 2 }, target, []), /savings or investment/);
assert.match(validate(form, source, { ...target, PrincipalBalance: null }, []), /balances/);
assert.match(validate(form, source, { ...target, InterestBalance: 0 }, []), /interest/);
assert.match(validate(form, source, target, [{ CustomerAccountId: "loan", Principal: 1, Interest: 0 }]), /principal/);
assert.match(validate(form, source, target, [{ CustomerAccountId: "loan", Principal: 0, Interest: 1 }]), /interest/);
assert.match(validate(form, source, target, [{ CustomerAccountId: "other", Principal: 90, Interest: 0 }]), /source balance/);
assert.equal(validate(form, { ...source, AvailableBalance: 120 }, target, []), "");
assert.match(validate(form, { ...source, AvailableBalance: 119.99 }, target, []), /source balance/);
assert.match(validate(form, { ...source, AvailableBalance: null }, target, []), /Refresh the source/);
assert.equal(validate(form, { ...source, CustomerAccountTypeProductCode: 3, BookBalance: 120 }, target, []), "");
assert.match(validate({ ...form, Principal: -1 }, source, target, []), /non-negative/);
assert.match(validate({ ...form, Principal: "NaN" }, source, target, []), /non-negative/);
assert.match(validate(form, source, { ...target, CustomerAccountTypeProductCode: 3 }, []), /interest only/);
assert.equal(validate({ ...form, Principal: 120, Interest: 0 }, source, { ...target, CustomerAccountTypeProductCode: 3 }, []), "");
assert.match(fs.readFileSync("src/lib/moduleRouteMap.js", "utf8"), /23049:\s*"\/Accounts\/IntraAccountTransfer"/);
assert.match(fs.readFileSync("src/App.jsx", "utf8"), /path="Accounts\/IntraAccountTransfer" element={<IntraAccountTransfer/);
console.log("Intra-account transfer checks passed: navigation, same customer, different account, supported products, source totals, loan limits, missing balances, and numeric validation.");
