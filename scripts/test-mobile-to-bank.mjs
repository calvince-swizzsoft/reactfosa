import assert from 'node:assert/strict';
import { build } from 'esbuild';
import vm from 'node:vm';
const calls = [];
const output = await build({ entryPoints: ['src/pages/Accounts/MobileToBank/api.js'], bundle: true, write: false, format: 'cjs', platform: 'node', define: { 'import.meta.env.VITE_APP_FIN_URL': '"https://test.invalid"' }, plugins: [{ name: 'mock-api', setup(build) { build.onResolve({ filter: /^@\/lib\/api$/ }, () => ({ path: 'api', namespace: 'mock' })); build.onLoad({ filter: /.*/, namespace: 'mock' }, () => ({ contents: 'export const apiJson = (...args) => globalThis.apiMock(...args);', loader: 'js' })); } }] });
const context = { exports: {}, module: { exports: {} }, URLSearchParams, apiMock: async (...args) => { calls.push(args); return { data: { Id: 'payment' } }; } };
vm.runInNewContext(output.outputFiles[0].text, context);
const api = context.module.exports;
assert.equal(api.canReconcile({ Status: 0, RecordStatus: 0 }), true);
for (const Status of [1,2]) assert.equal(api.canReconcile({ Status, RecordStatus: 0 }), false);
for (const RecordStatus of [2,3]) assert.equal(api.canReconcile({ Status: 0, RecordStatus }), false);
assert.equal(api.canReconcile(null), false);
await api.listPayments({ startDate: '2026-09-01', endDate: '2026-09-17', status: '0', text: '0712 & name', pageIndex: 2 });
let url = new URL(calls.at(-1)[0]);
assert.equal(url.searchParams.get('status'), '0');
assert.equal(url.searchParams.get('text'), '0712 & name');
assert.equal(url.searchParams.get('pageIndex'), '2');
assert.equal(url.searchParams.get('pageSize'), '20');
await api.listPayments({ status: '' });
assert.equal(new URL(calls.at(-1)[0]).searchParams.has('status'), false);
await api.reconcilePayment('payment', 'account');
assert.equal(calls.at(-1)[1].method, 'PUT');
assert.deepEqual(JSON.parse(calls.at(-1)[1].body), { CustomerAccountId: 'account' });
assert.equal(api.verificationStatus({ Status: 2, RecordStatus: 0 }), 'Pending verification');
assert.equal(api.matchingStatus({ Status: 1 }), 'Auto matched');
console.log('Mobile to Bank status guards and API contracts passed.');