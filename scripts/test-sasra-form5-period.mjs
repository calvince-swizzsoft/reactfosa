import assert from 'node:assert/strict';
import { latestCompletedQuarter, quarterEnd, validateForm5Dates, financialYearStart, reportingQuarters } from '../src/pages/Reports/GenerateSasraForm/form5Model.js';
assert.deepEqual(latestCompletedQuarter(new Date(2026, 8, 16)), { year: 2026, quarter: 2 });
assert.deepEqual(latestCompletedQuarter(new Date(2026, 0, 1)), { year: 2025, quarter: 4 });
assert.deepEqual(latestCompletedQuarter(new Date(2026, 3, 1)), { year: 2026, quarter: 1 });
for (const q of [1, 2, 3, 4]) assert.equal(validateForm5Dates('2026-01-01', quarterEnd(2026, q), 'Quarterly'), '');
assert.ok(validateForm5Dates('2026-01-01', '2026-09-16', 'Quarterly'));
assert.equal(validateForm5Dates('2026-01-01', '2026-09-16', 'Interim'), '');
assert.ok(validateForm5Dates('2026-01-01', '2026-09-30', 'Unknown'));
assert.ok(validateForm5Dates('2026-01-01', '2026-02-30', 'Interim'));
assert.equal(validateForm5Dates('2025-07-01', '2026-06-30', 'Quarterly'), '');
assert.ok(validateForm5Dates('2025-07-01', '2026-09-30', 'Quarterly'));
const periods = [{ durationStartDate: '2025-07-01T00:00:00', durationEndDate: '2026-06-30T00:00:00' }];
assert.equal(financialYearStart(periods, '2026-06-30'), '2025-07-01');
assert.equal(financialYearStart(periods, '2026-07-01'), '');
assert.equal(financialYearStart([], '2026-06-30'), '');
assert.equal(financialYearStart([...periods, { durationStartDate: '2026-01-01', durationEndDate: '2026-12-31' }], '2026-06-30'), '');
assert.equal(financialYearStart([...periods, ...periods], '2026-06-30'), '2025-07-01');
assert.ok(reportingQuarters([{ durationStartDate: '2010-07-01', durationEndDate: '2011-06-30' }], new Date(2026, 8, 16)).some(q => q.date === '2011-06-30'));
console.log('PASS Form 5 reporting periods and configured year resolution');
